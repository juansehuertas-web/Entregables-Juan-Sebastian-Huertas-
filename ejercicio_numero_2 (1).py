import pandas as pd

import numpy as np

df = pd.read_excel('/content/animal_data.xlsx')

"""Cantidad de filas"""

print("Filas:", df.shape[0])

"""Cantidad de columnas"""

print("Columnas:", df.shape[1])

"""Nombre de columnas y tipo de datos"""

print(df.dtypes)

"""Información general del dataframe"""

df.info()

"""Numero de valores faltantes por columna"""

df.isnull().sum()

"""Numero de valores duplicados por columna"""

df.duplicated().sum()

"""Identificación de categorias animales"""

print(df.iloc[:, 0].value_counts(dropna=False))

"""Identicación de categorias países"""

print(df["Country"].value_counts(dropna=False))

"""Identificación de categorias género"""

print(df["Gender"].value_counts(dropna=False))

"""Identificación de posibles inconsistencias en variables numericas"""

print(df["Weight kg"].describe())

print(df["Body Length cm"].describe())

"""Realización de las transformaciones necesarias para obtener una base de datos consistente

Creación de la copia para conservar datos originales y correción de nombres de columnas
"""

df_clean = df.copy()
df_clean.columns = df_clean.columns.str.replace("ï»¿", "", regex=False).str.strip()
print(df_clean.columns)

"""Eliminación de espacios innecesarios en las columnas de texto"""

for columna in df_clean.select_dtypes(include="object").columns:
   df_clean[columna] = df_clean[columna].str.strip()

print(df_clean.head())

"""Conversión de mayusculas a minusculas"""

df_clean["Animal type"] = df_clean["Animal type"].str.lower().str.strip()

"""Diccionario de correcciones"""

correcciones_animales = {
    "red squirrell": "red squirrel",
    "red squirel": "red squirrel",
    "lynx?": "lynx",
    "european bisonâ¢": "european bison",
    "european bisson": "european bison",
    "european buster": "european bison",
    "ledgehod": "hedgehog",
    "wedgehod": "hedgehog"
}

"""Aplicar las correciones"""

df_clean["Animal type"] = df_clean["Animal type"].replace(correcciones_animales)

print(df_clean["Animal type"].value_counts(dropna=False))

"""Unificacion de los nomres y codigos de países"""

correcciones_paises = {
    "PL": "Poland",
    "HU": "Hungary",
    "Hungry": "Hungary",
    "CZ": "Czech Republic",
    "Czech": "Czech Republic",
    "DE": "Germany"
}

df_clean["Country"] = df_clean["Country"].replace(correcciones_paises)

df_clean["Country"] = df_clean["Country"].replace({
    "Australia": np.nan,
    "CC": np.nan
})

print(df_clean["Country"].value_counts(dropna=False))

"""Estandarización de genero"""

df_clean["Gender"] = df_clean["Gender"].str.lower().str.strip()

df_clean["Gender"] = df_clean["Gender"].replace({
    "male": "Male",
    "female": "Female",
    "not determined": "Unknown"
})

print(df_clean["Gender"].value_counts(dropna=False))

"""Eliminación de resgistros duplicados"""

df_clean = df_clean.drop_duplicates()

print(df_clean.duplicated().sum())

print("Filas restantes:", len(df_clean))

"""Corrección de tipos de datos y valores invalidos"""

columnas_numericas = [
    "Weight kg",
    "Body Length cm",
    "Latitude",
    "Longitude"
]

df_clean.loc[:, columna] = pd.to_numeric(df_clean[columna])

df_clean.loc[:, "Observation date"] = pd.to_datetime(
    df_clean["Observation date"],
    format="%d.%m.%Y",
    errors="coerce"
)

"""Eliminación de pesos y longitudes negativas"""

df_clean.loc[df_clean["Weight kg"] < 0, "Weight kg"] = np.nan

df_clean.loc[df_clean["Body Length cm"] < 0, "Body Length cm"] = np.nan

"""Revisión de coordenadas geográficas fuera de un rango compatible con europa"""

df_clean.loc[
    ~df_clean["Latitude"].between(35, 72),
    "Latitude"
] = np.nan

df_clean.loc[
    ~df_clean["Longitude"].between(-25, 45),
    "Longitude"
] = np.nan

"""Eliminación de la columna animnal code por que esta vacia"""

df_clean = df_clean.drop(columns=["Animal code"])

print(df_clean.dtypes)

"""Los animales sin anymal type se eliminaron porque no es posible clasificarlos."""

df_clean = df_clean.dropna(subset=["Animal type"])

"""Los datos faltantes de peso y longitud se reemplazan por la mediana de la especie."""

for columna in ["Weight kg", "Body Length cm"]:

    medianas = df_clean.groupby("Animal type")[columna].transform("median")

    df_clean[columna] = df_clean[columna].fillna(medianas)

"""Se completp la categoria genero con not determined a los datos faltantes"""

df_clean["Gender"] = df_clean["Gender"].fillna("not determined")

"""Se completo la categoria country con unknown a los datos faltantes"""

df_clean["Country"] = df_clean["Country"].fillna("Unknown")

"""Comprovación de que la limpieza funciono"""

print("========== VERIFICACIÓN FINAL ==========")

print("\nDimensiones:")
print(df_clean.shape)

print("\nDuplicados:")
print(df_clean.duplicated().sum())

print("\nValores faltantes:")
print(df_clean.isnull().sum())

print("\nTipos de animales:")
print(df_clean["Animal type"].value_counts())

print("\nPaíses:")
print(df_clean["Country"].value_counts())

print("\nGéneros:")
print(df_clean["Gender"].value_counts())

print("\nEstadísticas numéricas:")
print(df_clean[["Weight kg", "Body Length cm"]].describe())

"""Creación de una variable utilizando np.where peso igual o superior a 100 kg heavy peso por debajo de 100 kg light"""

df_clean["Weight category"] = np.where(
    df_clean["Weight kg"] >= 100,
    "Heavy",
    "Light"
)

print(df_clean[["Animal type", "Weight kg", "Weight category"]].head())

"""Calculos estadisticos con NumPy"""

mediana_peso = np.median(df_clean["Weight kg"])

desviacion_peso = np.std(df_clean["Weight kg"])

print("Mediana del peso:", round(mediana_peso, 2), "kg")

print("Desviación estándar:", round(desviacion_peso, 2), "kg")

"""Interpretación:
np.median representa el valor central de los pesos cuando se ordenan de menor a mayor.
np.std representa cuánto se dispersan los pesos respecto al promedio.

Analisis con Groupby

Numero de observaciones por tipo de animal
"""

observaciones_animal = df_clean.groupby(
    "Animal type"
).size().sort_values(ascending=False)

print(observaciones_animal)

"""Peso promedio por tipo de animal"""

peso_por_animal = df_clean.groupby("Animal type")["Weight kg"].mean()
print(peso_por_animal)

"""Longitud promedio por tipo de animal"""

longitud_por_animal = df_clean.groupby(
    "Animal type"
)["Body Length cm"].mean().sort_values(ascending=False)
print(longitud_por_animal.round(2))

"""Peso promedio de cada animal por pais"""

